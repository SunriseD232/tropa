    [Fact]
    public void Owner_list_is_pasted_whole()
    {
        var r = GeoEdits.ParseAuto(OwnerList, ip: true, sites: true);
        Assert.Empty(r.Bad);
        Assert.Equal(["geosite:cloudflare"], r.GeoRefs);
        Assert.Contains(new GeoEntry(GeoEntryKind.Suffix, "connector_openai_cocoon.web-sandbox.oaiusercontent.com"), r.Entries);
        Assert.Contains(new GeoEntry(GeoEntryKind.Suffix, "rr1---sn-q4fl6n6z.googlevideo.com"), r.Entries);
        Assert.Contains(new GeoEntry(GeoEntryKind.Suffix, "spotify.com"), r.Entries);
        Assert.Contains(new GeoEntry(GeoEntryKind.Suffix, "xv-ru.com"), r.Entries);
        Assert.Contains(new GeoEntry(GeoEntryKind.Suffix, "cloud.microsoft"), r.Entries);
        // domain_suffix: — имя поля sing-box; «chatgpt» без точки — всё, что заканчивается на .chatgpt.
        Assert.Contains(new GeoEntry(GeoEntryKind.Suffix, "chatgpt"), r.Entries);
        Assert.All(r.Entries, e => Assert.Equal(GeoEntryKind.Suffix, e.Kind));
        Assert.Equal(r.Entries.Count, r.Entries.Distinct().Count());
    }
